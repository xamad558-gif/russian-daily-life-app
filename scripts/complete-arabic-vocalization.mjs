function normalize(value) {
  return value.normalize("NFC").replace(diacritics, "");
}

for (const [key, value] of vocabulary) vocabulary.set(normalize(key), value);
for (const [key, value] of levelExampleVocabulary) vocabulary.set(normalize(key), value);

function articleForm(token) {
  const bare = normalize(token.slice(2));
  const rootForm = vocabulary.get(bare);
  if (!rootForm) return null;
  const first = bare[0];
  if (sunLetters.has(first)) return `ال${first}ّ${rootForm.slice(1)}`;
  return `الْ${rootForm}`;
}

function vocalizeText(value, unknown) {
  return String(value || "").replace(arabicToken, (token) => {
    const key = normalize(token);
    const direct = vocabulary.get(key);
    if (direct) return direct;
    if (key.startsWith("ال")) {
      const article = articleForm(key);
      if (article) return article;
    }
    unknown.add(key);
    return token;
  });
}

const unitFile = JSON.parse(fs.readFileSync(dataPath, "utf8"));
const words = unitFile.words;
const unknown = new Set();
for (const word of words) {
  word.arabicVocalized = vocalizeText(word.arabic, unknown);
  word.exampleArVocalized = vocalizeText(word.exampleAr, unknown);
  for (const example of word.examples || []) example.arVocalized = vocalizeText(example.ar, unknown);
  for (const phrase of word.phrases || []) phrase.arVocalized = vocalizeText(phrase.ar, unknown);
}

if (unknown.size) {
  console.error(JSON.stringify({ status: "FAIL", unknownTokens: [...unknown].sort() }, null, 2));
  process.exit(1);
}

fs.writeFileSync(dataPath, `${JSON.stringify(unitFile, null, 2)}\n`, "utf8");
console.log(JSON.stringify({ status: "PASS", wordsUpdated: words.length, vocalizedFields: words.length * 8 }, null, 2));
