function populateSubcategories(){
  const seen = new Set();
  state.words.forEach(w => seen.add(w.subCategory));
  for (const sub of seen){
    const opt = document.createElement("option");
    opt.value = sub;
    els.subCategoryFilter.appendChild(opt);
  }
}
