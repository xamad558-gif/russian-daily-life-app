function playExampleAudio(w, index, lang){
  const ex = (w.examples || [])[index];
  if (!ex) return;
  const text = ex[lang] || "";
  const src = ex.audio && ex.audio[lang];
  const voice = { ar:"ar-SA", ru:"ru-RU", en:"en-US" }[lang];

  if (src) {
    const audio = new Audio(src);
    audio.play().catch(() => speak(text, voice));
  } else {
    speak(text, voice);
  }
}


