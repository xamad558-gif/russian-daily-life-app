function applyFilters(){
  const q = normalize(els.searchInput.value), sub = els.subCategoryFilter.value, level = els.levelFilter.value, sort = els.sortFilter.value;
  state.filtered = state.words.filter(w => {
    const hay = normalize([w.russian,w.transliteration,w.arabic,w.english,w.exampleRu,w.exampleAr,w.exampleEn].join(" "));
    return (!q || hay.includes(q)) && (sub === "all" || w.subCategory === sub) && (level === "all" || w.level === level);
  });
  if (sort === "az") state.filtered.sort((a,b)=>a.russian.localeCompare(b.russian,"ru"));
  if (sort === "za") state.filtered.sort((a,b)=>b.russian.localeCompare(a.russian,"ru"));
  if (sort === "default") state.filtered.sort((a,b)=>(b.frequency||0)-(a.frequency||0));
  if (sort === "mastery") state.filtered.sort((a,b)=>(state.mastery[a.id]||0)-(state.mastery[b.id]||0));
  if (!state.filtered.find(w => w.id === state.selectedWordId)) state.selectedWordId = state.filtered[0]?.id || null;
  const t = I18N[state.uiLang];
  els.pageCounter.textContent = `${state.filtered.length} ${t.pageCounterWord}`;
  els.emptyState.classList.toggle("hidden", state.filtered.length > 0);
  renderCards();
  renderDetail();
  updateMetrics();
}
